it.each(['save', 'close', 'escape'])('restores playlist-trigger focus without a lingering tooltip after %s', async method => {
  await session()
  vi.stubGlobal('fetch', vi.fn(async (input: string) => Response.json({ response: input.includes('getPlaylists') ? { count: 1, items: [saved] } : [{ audio_id: 20 }] })))
  const { AddTrackToPlaylistButton } = await import('@/features/manage-playlists')
  const { client } = await mount(createElement(AddTrackToPlaylistButton, { track: track('-2_20') }))
  const button = await screen.findByRole('button', { name: 'Добавить в плейлист' })
  act(() => { button.focus() })
  await screen.findByRole('tooltip', { hidden: true })
  fireEvent.click(button)
  const dialog = await screen.findByRole('dialog', { name: 'Добавить в плейлист' })
  await waitFor(() => { expect(dialog.contains(document.activeElement)).toBe(true) })
  if (method === 'save') fireEvent.click(await screen.findByText('My playlist'))
  else if (method === 'close') fireEvent.click(screen.getByRole('button', { name: 'Отмена' }))
  else fireEvent.keyDown(document.activeElement ?? document, { key: 'Escape', code: 'Escape', keyCode: 27 })
  await waitFor(() => { expect(screen.queryByRole('dialog')).toBeNull() })
  await waitFor(() => { expect(document.activeElement).toBe(button) })
  await waitFor(() => { expect(screen.queryByRole('tooltip', { hidden: true })).toBeNull() })
  fireEvent.mouseOut(button, { relatedTarget: document.body })
  fireEvent.mouseOver(button)
  await screen.findByRole('tooltip', { hidden: true })
  fireEvent.mouseOut(button, { relatedTarget: document.body })
  act(() => { button.blur() })
  await waitFor(() => { expect(screen.queryByRole('tooltip', { hidden: true })).toBeNull() })
  act(() => { button.focus() })
  await screen.findByRole('tooltip', { hidden: true })
  await act(async () => { client.clear() })
})
